#!/usr/bin/env python3
"""Convert a storyboard CSV into a typed scenes data file for Remotion.

Usage:
    python storyboard_to_scenes.py storyboard.csv src/data/scenes.ts [--fps 30]

Optional columns: `label` (on-screen chapter label, in the video's language; empty = none), `kind` (hook, stat, steps, compare, question, definition, quote,
recap, concept) and `assets` (public/ file names separated by `|`).
Writes a TypeScript module exporting `FPS`, `scenes` (with startFrame/durationFrames)
and `TOTAL_FRAMES`, so composition length always equals the storyboard.
"""
import argparse
import csv
import json


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("csv_path")
    ap.add_argument("out_path")
    ap.add_argument("--fps", type=int, default=30)
    a = ap.parse_args()

    scenes = []
    with open(a.csv_path, newline="", encoding="utf-8-sig") as f:
        for r in csv.DictReader(f):
            s, e = float(r["start_seconds"]), float(r["end_seconds"])
            start, end = round(s * a.fps), round(e * a.fps)
            scenes.append({
                "id": r["scene"].strip(),
                "title": r.get("learning_purpose", "").strip(),
                "label": r.get("label", "").strip(),
                "visual": r.get("visual", "").strip(),
                "narration": r.get("narration", "").strip(),
                "onScreenText": r.get("on_screen_text", "").strip(),
                "kind": (r.get("kind") or "concept").strip(),
                "assets": [x.strip() for x in (r.get("assets") or "").split("|") if x.strip()],
                "startFrame": start,
                "durationFrames": max(1, end - start),
            })
    total = max((s["startFrame"] + s["durationFrames"] for s in scenes), default=1)
    body = json.dumps(scenes, indent=2, ensure_ascii=False)
    ts = (
        "// Generated by storyboard_to_scenes.py - edit the CSV, then regenerate.\n"
        "export type SceneData = {\n  id: string;\n  title: string;\n  label: string;\n  visual: string;\n"
        "  narration: string;\n  onScreenText: string;\n  kind: string;\n  assets: string[];\n  startFrame: number;\n  durationFrames: number;\n};\n\n"
        f"export const FPS = {a.fps};\n"
        f"export const TOTAL_FRAMES = {total};\n"
        f"export const scenes: SceneData[] = {body};\n"
    )
    with open(a.out_path, "w", encoding="utf-8") as f:
        f.write(ts)
    print(f"Wrote {len(scenes)} scenes, {total} frames -> {a.out_path}")


if __name__ == "__main__":
    main()
